import http.cookiejar
import json
import os
import secrets
import shutil
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = HERE / ".data"
SECRETS = DATA / "secrets"
ENV_FILE = DATA / "quickstart.env"
COMPOSE = HERE / "compose.yaml"
DEMO_EMAIL = "demo@example.com"
DEMO_NAME = "Demo"
DEMO_KEY = "demo"           # SparkyFitness key name -> secrets/sparkyfitness_api_key_demo_ro
# Host the script itself uses to reach the published ports (printed links always say localhost). Set W2W_PROBE_HOST
# when the Docker engine is not on this machine's loopback, e.g. host.docker.internal from inside a container.
PROBE = os.environ.get("W2W_PROBE_HOST", "localhost")
PORTS = {"W2W_BODY_PORT": 18100, "W2W_OW_PORT": 18200, "W2W_SF_PORT": 18300, "W2W_GRAFANA_PORT": 18400}


def local_timezone() -> str:
    """IANA name of the host's time zone (the Today page uses the browser's date, so the demo user should match)."""
    if os.environ.get("TZ") and "/" in os.environ["TZ"]:
        return os.environ["TZ"].lstrip(":")
    try:
        target = os.path.realpath("/etc/localtime")
        if "zoneinfo/" in target:
            return target.split("zoneinfo/", 1)[1]
    except OSError:
        pass
    try:
        return Path("/etc/timezone").read_text().strip() or "UTC"
    except OSError:
        return "UTC"


def say(msg: str) -> None:
    print(f"\033[1m==>\033[0m {msg}", flush=True)


def die(msg: str) -> None:
    print(f"\033[31merror:\033[0m {msg}", file=sys.stderr)
    sys.exit(1)


# ------------------------------------------------------------------ env / secrets
def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    return dict(line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line and not line.startswith("#"))


def write_private(path: Path, text: str) -> None:
    """Create or overwrite in place (keeps the inode, so a running container's secret mount sees the change)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)


def port_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind(("127.0.0.1", port))
            return True
        except OSError:
            return False


def choose_ports(env: dict[str, str], running: bool) -> dict[str, str]:
    """Saved ports win (the stack may already hold them); otherwise env override, else the first free port >= default."""
    out = {}
    taken: set[int] = set()
    for key, default in PORTS.items():
        if key in env:
            out[key] = env[key]
            continue
        want = int(os.environ.get(key, default))
        port = want
        while not port_free(port) or port in taken:
            if key in os.environ:
                die(f"port {port} ({key}) is in use; pick another one, e.g. {key}={port + 1} ./quickstart.sh")
            port += 1
        if port != want:
            print(f"    port {want} is busy, using {port} for {key}")
        taken.add(port)
        out[key] = str(port)
    return out


def ensure_config(tz: str) -> dict[str, str]:
    env = read_env()
    running = bool(compose_ps())
    first = not env
    env.setdefault("W2W_PROJECT", os.environ.get("W2W_PROJECT", "watch2whoop-quickstart"))
    env.setdefault("W2W_TZ", tz)
    env.update(choose_ports(env, running))
    for key in ("OW_DB_PASSWORD", "SPARKY_FITNESS_DB_PASSWORD", "SPARKY_FITNESS_APP_DB_PASSWORD"):
        env.setdefault(key, secrets.token_hex(24))
    env.setdefault("SPARKY_FITNESS_API_ENCRYPTION_KEY", secrets.token_hex(32))
    env.setdefault("BETTER_AUTH_SECRET", secrets.token_urlsafe(48))
    env.setdefault("SPARKY_FITNESS_ADMIN_EMAIL", DEMO_EMAIL)
    write_private(ENV_FILE, "# generated by quickstart/run.py; delete with ./quickstart.sh reset\n"
                  + "".join(f"{k}={v}\n" for k, v in env.items()))

    ow_env = DATA / "open_wearables.env"
    if not ow_env.exists():
        lines = []
        gen = {"DB_PASSWORD": env["OW_DB_PASSWORD"], "SECRET_KEY": secrets.token_urlsafe(64)}
        for line in (ROOT / "deploy/open-wearables/.env.example").read_text().splitlines():
            key, _, value = line.partition("=")
            if line.startswith("#") or not _:
                lines.append(line)
                continue
            if key in gen:
                value = gen[key]
            elif value == "__GENERATE__":
                value = secrets.token_hex(24)
            value = {"DB_HOST": "ow-db", "REDIS_HOST": "ow-redis", "ADMIN_EMAIL": "admin@example.com",
                     "API_BASE_URL": f"http://localhost:{env['W2W_OW_PORT']}"}.get(key, value)
            lines.append(f"{key}={value}")
        write_private(ow_env, "\n".join(lines) + "\n")

    for name, make in (("body_db_password", lambda: secrets.token_hex(24)),
                       ("ai_master_key", lambda: secrets.token_bytes(32).hex()),
                       ("grafana_admin_password", lambda: secrets.token_urlsafe(18)),
                       ("grafana_ro_body_password", lambda: secrets.token_hex(24)),
                       ("grafana_ro_ow_password", lambda: secrets.token_hex(24)),
                       ("open_wearables_api_key", lambda: ""),
                       (f"sparkyfitness_api_key_{DEMO_KEY}_ro", lambda: ""),
                       (f"sparkyfitness_api_key_{DEMO_KEY}_rw", lambda: "")):
        p = SECRETS / name
        if not p.exists():
            write_private(p, make())
    (DATA / "health" / "archive").mkdir(parents=True, exist_ok=True)
    (DATA / "health" / "imports").mkdir(parents=True, exist_ok=True)
    if first:
        say(f"generated random secrets in {DATA.relative_to(ROOT)}/")
    return env


# ------------------------------------------------------------------ docker
def compose_cmd(*args: str, env_extra: dict | None = None, profiles: tuple = ()) -> list[str]:
    cmd = ["docker", "compose", "--env-file", str(ENV_FILE), "-f", str(COMPOSE)]
    for p in profiles:
        cmd += ["--profile", p]
    return cmd + list(args)


def compose(*args: str, check=True, capture=False, input_bytes: bytes | None = None, env_extra: dict | None = None,
            profiles: tuple = ()) -> subprocess.CompletedProcess:
    env = {**os.environ, **(env_extra or {})}
    return subprocess.run(compose_cmd(*args, profiles=profiles), check=check, env=env, input=input_bytes,
                          stdout=subprocess.PIPE if capture else None, stderr=subprocess.PIPE if capture else None)


def compose_ps() -> list[str]:
    if not ENV_FILE.exists():
        return []
    r = compose("ps", "--services", "--status", "running", check=False, capture=True)
    return r.stdout.decode().split() if r.returncode == 0 else []


def engine(*args: str, capture=True) -> str:
    r = compose("exec", "-T", "body-engine", "body-engine", *args, check=False, capture=capture)
    if r.returncode != 0:
        die(f"body-engine {' '.join(args)} failed:\n{(r.stderr or b'').decode()[-2000:]}")
    return (r.stdout or b"").decode()


def wait_http(url: str, what: str, timeout: int = 300) -> None:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=5) as r:
                if r.status < 500:
                    return
        except urllib.error.HTTPError as e:
            if e.code < 500:
                return
        except Exception:
            pass
        time.sleep(2)
    die(f"{what} did not come up at {url}; see ./quickstart.sh logs")


def check_prereqs() -> None:
    if sys.version_info < (3, 9):
        die("python3 >= 3.9 is required")
    if not shutil.which("docker"):
        die("Docker is not installed (https://docs.docker.com/get-docker/)")
    if subprocess.run(["docker", "info"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode != 0:
        die("the Docker daemon is not running (start Docker Desktop / dockerd)")
    if subprocess.run(["docker", "compose", "version"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode:
        die("Docker Compose v2 is required (`docker compose version`)")


# ------------------------------------------------------------------ Open Wearables
def setup_ow(env: dict) -> None:
    key_file = SECRETS / "open_wearables_api_key"
    if key_file.read_text().strip():
        return
    say("Open Wearables: creating an API key for Body Engine")
    script = (ROOT / "deploy/open-wearables/bootstrap.py").read_bytes()
    for _ in range(30):
        r = compose("exec", "-T", "ow-app", "uv", "run", "python", "-", "api-key", "body-engine", check=False,
                    capture=True, input_bytes=script)
        key = r.stdout.decode().strip().splitlines()[-1:] if r.returncode == 0 else []
        if key and key[0]:
            write_private(key_file, key[0] + "\n")
            return
        time.sleep(5)
    die(f"could not create the Open Wearables API key:\n{r.stderr.decode()[-1500:]}")


# ------------------------------------------------------------------ SparkyFitness
class SparkySession:
    def __init__(self, base: str, origin: str):
        self.base, self.origin = base, origin
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, method: str, path: str, body: dict | None = None, headers: dict | None = None):
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(self.base + path, data=data, method=method, headers={
            "Content-Type": "application/json", "Accept": "application/json", "Origin": self.origin, **(headers or {})})
        try:
            with self.opener.open(req, timeout=60) as resp:
                text = resp.read().decode()
                return resp.status, (json.loads(text) if text else None)
        except urllib.error.HTTPError as e:
            text = e.read().decode(errors="replace")
            try:
                return e.code, json.loads(text)
            except ValueError:
                return e.code, text


def setup_sparky(env: dict, profiles: tuple) -> None:
    ro = SECRETS / f"sparkyfitness_api_key_{DEMO_KEY}_ro"
    if ro.read_text().strip():
        return
    base = f"http://{PROBE}:{env['W2W_SF_PORT']}"
    pw_file = SECRETS / "sparkyfitness_demo_password"
    if not pw_file.exists():
        write_private(pw_file, secrets.token_urlsafe(18) + "\n")
    password = pw_file.read_text().strip()
    wait_http(base + "/api/health", "SparkyFitness")
    s = SparkySession(base, f"http://localhost:{env['W2W_SF_PORT']}")
    status, body = s.call("POST", "/api/auth/sign-in/email", {"email": DEMO_EMAIL, "password": password})
    if status != 200:
        say("SparkyFitness: creating the demo account (sign-up is opened only for this step)")
        compose("up", "-d", "sparkyfitness-server", env_extra={"SF_DISABLE_SIGNUP": "false"}, profiles=profiles)
        wait_http(base + "/api/health", "SparkyFitness")
        try:
            for _ in range(20):
                status, body = s.call("POST", "/api/auth/sign-up/email",
                                      {"email": DEMO_EMAIL, "password": password, "name": DEMO_NAME})
                if status == 200:
                    break
                time.sleep(3)
            else:
                die(f"SparkyFitness sign-up failed: {status} {body}")
        finally:
            compose("up", "-d", "sparkyfitness-server", profiles=profiles)
            wait_http(base + "/api/health", "SparkyFitness")
        status, body = s.call("POST", "/api/auth/sign-in/email", {"email": DEMO_EMAIL, "password": password})
        if status != 200:
            die(f"SparkyFitness sign-in failed: {status} {body}")
    for scope, suffix in (("full", "rw"), ("read", "ro")):
        key_file = SECRETS / f"sparkyfitness_api_key_{DEMO_KEY}_{suffix}"
        if key_file.exists() and key_file.read_text().strip():
            continue
        status, res = s.call("POST", "/api/identity/user/generate-api-key",
                             {"name": f"body-engine-{suffix}", "expiresIn": None, "scope": scope})
        if status != 201:
            die(f"SparkyFitness API key failed: {status} {res}")
        write_private(key_file, res["apiKey"]["key"] + "\n")


# ------------------------------------------------------------------ Body Engine
def demo_user_id() -> int | None:
    for line in engine("user-list").splitlines():
        try:
            u = json.loads(line)
        except ValueError:
            continue
        if u.get("display_name") == DEMO_NAME:
            return int(u["id"])
    return None


def setup_body(env: dict, days: int, sparky: bool) -> int:
    uid = demo_user_id()
    if uid is None:
        say("Body Engine: creating the demo user")
        engine("user-add", "--name", DEMO_NAME, "--role", "owner", "--timezone", env["W2W_TZ"],
               "--birth-date", "1990-01-01", "--height-cm", "178", "--sex", "male")
        uid = demo_user_id()
        if uid is None:
            die("could not find the demo user after user-add")
    marker = DATA / f"demo_loaded_u{uid}"
    if not marker.exists():
        say(f"generating {days} days of synthetic Apple Health data (no real person's data)")
        zip_path = DATA / "demo-export.zip"
        subprocess.run([sys.executable, str(HERE / "demo_data.py"), "--days", str(days), "--tz", env["W2W_TZ"],
                        "--out", str(zip_path)], check=True)
        (DATA / "health" / "imports" / "demo-export.zip").write_bytes(zip_path.read_bytes())
        say("importing it through the real Apple Health importer and computing scores")
        engine("import-apple-zip", "--user-id", str(uid), "--file", "/data/health/imports/demo-export.zip")
        (DATA / "health" / "imports" / "demo-export.zip").unlink()
        engine("journal-init", "--user-id", str(uid))
        if sparky:
            engine("sparky-link", "--user-id", str(uid), "--key-name", DEMO_KEY)
        engine("ow-link", "--user-id", str(uid))
        engine("memory-init", "--user-id", str(uid))
        engine("set-sleep-goal", "--user-id", str(uid), "--bedtime", "23:00")
        marker.write_text("ok\n")
    sparky_marker = DATA / f"demo_sparky_u{uid}"
    if not sparky_marker.exists():
        say("adding synthetic meals, strength sessions and weigh-ins" + (" to SparkyFitness" if sparky else ""))
        r = compose("exec", "-T", "body-engine", "python", "-", str(uid), check=False, capture=True,
                    input_bytes=(HERE / "demo_sparky.py").read_bytes())
        if r.returncode != 0:
            die(f"demo food / workout / weight data failed:\n{r.stderr.decode()[-2000:]}")
        print("    " + r.stdout.decode().strip())
        sparky_marker.write_text("ok\n")
    engine("refresh-status", "--user-id", str(uid))
    engine("evaluate-rules", "--user-id", str(uid))
    return uid


def login_link(env: dict, uid: int) -> str:
    out = engine("login-code", "--user-id", str(uid), "--label", "quickstart", "--hours", "24")
    code = out.strip().splitlines()[0].strip() if out.strip() else ""
    if not code:
        die("could not read the login code from `body-engine login-code`")
    return f"http://localhost:{env['W2W_BODY_PORT']}/app/#login={code}"


def summary(env: dict, uid: int, grafana: bool, sparky: bool = False) -> None:
    link = login_link(env, uid)
    print(f"""
\033[1mWatch2Whoop is running.\033[0m
  Today page (one-time login link, valid 24 h):  {link}
  Body Engine API docs:                          http://localhost:{env['W2W_BODY_PORT']}/docs
  Open Wearables API:                            http://localhost:{env['W2W_OW_PORT']}/docs""")
    if sparky:
        print(f"  SparkyFitness (back end, demo@example.com):    http://localhost:{env['W2W_SF_PORT']}   password: quickstart/.data/secrets/sparkyfitness_demo_password")
    if grafana:
        print(f"  Grafana (admin):                               http://localhost:{env['W2W_GRAFANA_PORT']}   password: quickstart/.data/secrets/grafana_admin_password")
    print("""
  New login link:  ./quickstart.sh login        Stop: ./quickstart.sh down        Remove everything: ./quickstart.sh reset
  All data shown is synthetic. Read the README for connecting a real watch.""")


# ------------------------------------------------------------------ Grafana
def setup_grafana() -> None:
    """Give the read-only grafana_ro roles a password (Body Engine's role comes from migration 050; OW's from ow_grafana_ro.sql)."""
    say("Grafana: enabling the read-only database roles")
    body_pw = (SECRETS / "grafana_ro_body_password").read_text().strip()
    ow_pw = (SECRETS / "grafana_ro_ow_password").read_text().strip()
    compose("exec", "-T", "body-db", "psql", "-q", "-v", "ON_ERROR_STOP=1", "-U", "body", "-d", "body",
            input_bytes=f"ALTER ROLE grafana_ro WITH LOGIN PASSWORD '{body_pw}';\n".encode(), capture=True)
    sql = (ROOT / "deploy/grafana/ow_grafana_ro.sql").read_bytes()
    sql += f"\nALTER ROLE grafana_ro WITH LOGIN PASSWORD '{ow_pw}';\n".encode()
    compose("exec", "-T", "ow-db", "psql", "-q", "-v", "ON_ERROR_STOP=1", "-U", "open-wearables", "-d", "open-wearables",
            input_bytes=sql, capture=True)


# ------------------------------------------------------------------ commands
ALL_PROFILES = ("grafana", "sparkyfitness")


def cmd_up(a) -> None:
    check_prereqs()
    env = ensure_config(a.tz)
    profiles = (("grafana",) if a.grafana else ()) + (("sparkyfitness",) if a.sparkyfitness else ())
    say(f"starting containers (project {env['W2W_PROJECT']}; first run builds Body Engine and pulls images, ~5 min)")
    compose("up", "-d", "--build", profiles=profiles)
    wait_http(f"http://{PROBE}:{env['W2W_BODY_PORT']}/healthz", "Body Engine")
    wait_http(f"http://{PROBE}:{env['W2W_OW_PORT']}/api/v1/health", "Open Wearables", timeout=600)
    setup_ow(env)
    if a.sparkyfitness:
        setup_sparky(env, profiles)
    else:   # issue #252: the logs live in Body Engine's own tables, nothing is written to SparkyFitness
        engine("flags", "set", "own_food_only", "--state", "all", "--by", "quickstart")
    uid = setup_body(env, a.days, a.sparkyfitness)
    if a.grafana:
        setup_grafana()
    summary(env, uid, a.grafana, a.sparkyfitness)


def cmd_login(a) -> None:
    env = read_env()
    if not env or "body-engine" not in compose_ps():
        die("the Quick Start stack is not running; start it with ./quickstart.sh")
    uid = demo_user_id()
    print(login_link(env, uid))


def main() -> None:
    p = argparse.ArgumentParser(prog="quickstart.sh", description="Run Watch2Whoop locally with synthetic demo data.")
    p.add_argument("command", nargs="?", default="up", choices=["up", "login", "status", "logs", "down", "reset"])
    p.add_argument("service", nargs="?", help="for logs: one service name")
    p.add_argument("--grafana", action="store_true", help="also start Grafana")
    p.add_argument("--sparkyfitness", action="store_true",
                   help="also start SparkyFitness and keep the demo logs there (optional, no longer needed)")
    p.add_argument("--days", type=int, default=60, help="days of synthetic data (default 60)")
    p.add_argument("--tz", default=os.environ.get("W2W_TZ") or local_timezone(),
                   help="demo user's IANA time zone (default: this machine's)")
    p.add_argument("--yes", action="store_true", help="reset without asking")
    a = p.parse_args()
    if a.command == "up":
        cmd_up(a)
    elif a.command == "login":
        cmd_login(a)
    elif not ENV_FILE.exists():
        die("nothing to do: the Quick Start stack was never started here")
    elif a.command == "status":
        compose("ps", profiles=ALL_PROFILES)
    elif a.command == "logs":
        compose("logs", "--tail", "200", *( [a.service] if a.service else []), profiles=ALL_PROFILES)
    elif a.command == "down":
        compose("down", profiles=ALL_PROFILES)
    elif a.command == "reset":
        if not a.yes and input("Delete the Quick Start containers, volumes and quickstart/.data/? [y/N] ").lower() != "y":
            return
        compose("down", "-v", "--remove-orphans", profiles=ALL_PROFILES)
        shutil.rmtree(DATA)
        say("removed")


if __name__ == "__main__":
    main()
