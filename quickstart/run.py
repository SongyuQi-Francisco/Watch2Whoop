#!/usr/bin/env python3
"""Watch2Whoop Quick Start: one command from a fresh clone to a running Today page with demo data.

    ./quickstart.sh                 start everything, create the demo user, load synthetic data, print the login link
    ./quickstart.sh --grafana       also start Grafana
    ./quickstart.sh --sparkyfitness also start SparkyFitness (optional: food / weight / workout logs live in Body Engine)
    ./quickstart.sh login           print a fresh one-time login link
    ./quickstart.sh status | logs [service] | down | reset

Requirements: Docker with Compose v2, python3 >= 3.9. Nothing is installed on the host.
State lives in quickstart/.data/ (git-ignored): generated secrets, the env file with the chosen ports,
the demo export. `reset` removes the containers, their volumes and quickstart/.data/.
Standard library only.
"""
from __future__ import annotations

