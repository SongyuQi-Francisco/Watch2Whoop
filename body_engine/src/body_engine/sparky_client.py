"""Client for SparkyFitness (workout, food and weight records): standard library only. Reads use a read-only key;
writes (the butler's log_food / log_workout / log_weight, assistant/sparky_write.py) get a read-write key from write_client_for_user.

Why the API rather than a read-only database role:
- SparkyFitness tables separate users by Postgres row-level security (RLS), and the application role must set the current user before each query;
  adding a read-only role that bypasses RLS would let Body Engine see every family member's data, and authorization would have to be redone here.
- It is maintained by one person and updates fast, with frequent incompatible schema changes (dozens of workout columns added in the last half year); the API at least has a zod contract and docs.
- Since 1.8.0 there are "read-only API keys": the server enforces GET only, one per person, which maps neatly to Body Engine's "one token per person".
- The database port does not need to be exposed.

One read-only key per person, in secrets/sparkyfitness_api_key_<users.sparky_key_name>_ro (generated by deploy/sparkyfitness/bootstrap.py);
`body-engine sparky-link --user-id 1 --key-name owner` validates the key and records the SparkyFitness user id.
The address is BODY_SPARKY_URL, default http://127.0.0.1:8300 (inside the container use http://host.docker.internal:8300).
Dates are local dates in SparkyFitness (user time zone Australia/Sydney).
"""
import json
import os
import urllib.error
import urllib.parse
import urllib.request
import uuid
from datetime import date, timedelta
from pathlib import Path

import psycopg

from .config import REPO_ROOT

SPARKY_URL = os.environ.get("BODY_SPARKY_URL", "http://127.0.0.1:8300")
SECRETS_DIR = Path(os.environ.get("BODY_SECRETS_DIR", REPO_ROOT / "secrets"))
HISTORY_PAGE = 100  # pageSize upper limit of /v2/exercise-entries/history


class SparkyError(RuntimeError):
    pass


class SparkyClient:
    def __init__(self, api_key: str, base_url: str | None = None, timeout: float = 60):
        self.base_url = (base_url or SPARKY_URL).rstrip("/") + "/api"
        self.api_key = api_key
        self.timeout = timeout

    def get(self, path: str, **params):
        return self.request("GET", path, params=params)

    def request(self, method: str, path: str, body=None, params: dict | None = None,
                multipart_field: str | None = None):
        """Send a request and return parsed JSON (None for an empty response). Writes can only be done with a read-write key (enforced by the server).
        multipart_field: some SparkyFitness endpoints (creating an exercise) require the JSON to be placed in one field of a multipart body."""
        url = self.base_url + path
        if params:
            url += "?" + urllib.parse.urlencode({k: v for k, v in params.items() if v is not None})
        headers = {"Authorization": f"Bearer {self.api_key}", "Accept": "application/json"}
        data = None
        if multipart_field is not None:
            boundary = uuid.uuid4().hex
            headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
            data = (f"--{boundary}\r\nContent-Disposition: form-data; name=\"{multipart_field}\"\r\n\r\n"
                    f"{json.dumps(body, ensure_ascii=False)}\r\n--{boundary}--\r\n").encode()
        elif body is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(body, ensure_ascii=False).encode()
        req = urllib.request.Request(url, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                text = resp.read().decode()
                return json.loads(text) if text else None
        except urllib.error.HTTPError as e:
            raise SparkyError(f"{method} {path} → {e.code}: {e.read()[:300].decode(errors='replace')}") from e
        except urllib.error.URLError as e:
            raise SparkyError(f"连不上 SparkyFitness（{self.base_url}）：{e.reason}") from e

    def whoami(self) -> dict:
        """The user the current key belongs to; also confirms it is a read-only key (with API key login, session.id is the key's id)."""
        session = self.get("/auth/get-session")
        keys = {k["id"]: k for k in self.get("/identity/user-api-keys")}
        perms = (keys.get(session["session"]["id"]) or {}).get("permissions") or {}
        if perms.get("sparky") != ["read"]:
            raise SparkyError("这把 SparkyFitness API key 不是只读的，Body Engine 只用只读 key")
        return session["user"]


def key_file(key_name: str, kind: str = "ro") -> Path:
    return SECRETS_DIR / f"sparkyfitness_api_key_{key_name}_{kind}"


def client_for_user(conn: psycopg.Connection, user_id: int) -> SparkyClient:
    row = conn.execute("SELECT sparky_key_name FROM users WHERE id = %s", (user_id,)).fetchone()
    if row is None:
        raise ValueError(f"没有用户 {user_id}")
    if not row["sparky_key_name"]:
        raise SparkyError(f"用户 {user_id} 还没连 SparkyFitness：body-engine sparky-link --user-id {user_id} --key-name ...")
    path = key_file(row["sparky_key_name"])
    if not path.exists():
        raise SparkyError(f"找不到 SparkyFitness 只读 key：{path}（deploy/sparkyfitness/bootstrap.py 生成）")
    return SparkyClient(path.read_text().strip())


_verified_rw: set[tuple[str, str]] = set()  # (key file, SparkyFitness user id): read-write keys already validated in this process


def write_client_for_user(conn: psycopg.Connection, user_id: int) -> SparkyClient:
    """Client for writing SparkyFitness: the read-write key (secrets/sparkyfitness_api_key_<name>_rw).
    Only for the butler's write tools (the user confirms in the client before every write); before writing, confirm this key logs in as the account recorded by sparky-link,
    so a misplaced key cannot write data into someone else's account."""
    row = conn.execute("SELECT sparky_key_name, sparky_user_id FROM users WHERE id = %s", (user_id,)).fetchone()
    if row is None:
        raise ValueError(f"没有用户 {user_id}")
    if not row["sparky_key_name"] or not row["sparky_user_id"]:
        raise SparkyError(f"用户 {user_id} 还没连 SparkyFitness：body-engine sparky-link --user-id {user_id} --key-name ...")
    path = key_file(row["sparky_key_name"], "rw")
    if not path.exists():
        raise SparkyError(f"找不到 SparkyFitness 读写 key：{path}（deploy/sparkyfitness/bootstrap.py 生成）")
    client = SparkyClient(path.read_text().strip())
    if (str(path), row["sparky_user_id"]) not in _verified_rw:
        sparky_user = client.get("/auth/get-session")["user"]["id"]
        if sparky_user != row["sparky_user_id"]:
            raise SparkyError(f"{path.name} 登录的不是用户 {user_id} 连的 SparkyFitness 账号，不写")
        _verified_rw.add((str(path), row["sparky_user_id"]))
    return client


def link_user(conn: psycopg.Connection, user_id: int, key_name: str, client: SparkyClient | None = None) -> str:
    """Validate the read-only key (can log in and is really read-only), record users.sparky_user_id / sparky_key_name."""
    if conn.execute("SELECT 1 FROM users WHERE id = %s", (user_id,)).fetchone() is None:
        raise ValueError(f"没有用户 {user_id}")
    client = client or SparkyClient(key_file(key_name).read_text().strip())
    sparky_user_id = client.whoami()["id"]
    conn.execute("UPDATE users SET sparky_user_id = %s, sparky_key_name = %s WHERE id = %s",
                 (sparky_user_id, key_name, user_id))
    return sparky_user_id


# ---------------------------------------------------------------- workouts
def _set(s: dict) -> dict:
    return {"id": s.get("id"), "set": s["set_number"], "type": s.get("set_type"), "reps": s.get("reps"), "weight_kg": s.get("weight"),
            "rir": s.get("rir"), "rpe": s.get("rpe"), "duration_s": s.get("duration"),
            "distance_km": s.get("distance"), "notes": s.get("notes")}


def _exercise(e: dict) -> dict:
    snap = e.get("exercise_snapshot") or {}
    return {"entry_id": e.get("id"), "exercise_id": e.get("exercise_id"), "name": snap.get("name") or e.get("name"),
            "category": snap.get("category") or e.get("category"), "primary_muscles": snap.get("primary_muscles"),
            "notes": e.get("notes"),
            "superset_group": e.get("superset_group"), "duration_minutes": e.get("duration_minutes"),
            "calories_burned": e.get("calories_burned"), "avg_heart_rate": e.get("avg_heart_rate"),
            "sets": [_set(s) for s in sorted(e.get("sets") or [], key=lambda s: s["set_number"])]}


def _session(s: dict) -> dict:
    if s["type"] == "preset":
        exercises = [_exercise(e) for e in s["exercises"]]
        return {"id": s.get("id"), "date": s["entry_date"], "name": s["name"], "notes": s.get("notes"), "source": s.get("source"),
                "total_duration_minutes": s.get("total_duration_minutes"), "exercises": exercises}
    ex = _exercise(s)  # A single exercise (cardio, standalone exercise)
    return {"id": s.get("id"), "date": s["entry_date"], "name": s.get("name") or ex["name"], "notes": None, "source": s.get("source"),
            "total_duration_minutes": s.get("duration_minutes"), "exercises": [ex]}


def training_log(client: SparkyClient, start: date, end: date) -> list[dict]:
    """Workout records in [start, end] (ascending by date); each workout contains exercises and per-set reps, weight, RIR."""
    out, page = [], 1
    while True:
        res = client.get("/v2/exercise-entries/history", page=page, pageSize=HISTORY_PAGE)
        sessions = res["sessions"]
        for s in sessions:  # Descending by date
            d = date.fromisoformat(s["entry_date"][:10])
            if start <= d <= end:
                out.append(_session(s))
        if not res["pagination"]["hasMore"] or not sessions or date.fromisoformat(sessions[-1]["entry_date"][:10]) < start:
            break
        page += 1
    return sorted(out, key=lambda s: s["date"])


# ---------------------------------------------------------------- food
def _food_entry(e: dict) -> dict:
    qty, serving = e.get("quantity") or 0, e.get("serving_size") or 1
    scale = qty / serving if serving else 0
    total = lambda k: None if e.get(k) is None else round(e[k] * scale, 1)
    return {"id": e.get("id"), "source": e.get("source"), "date": e["entry_date"][:10], "time": (e.get("entry_time") or "")[:5] or None, "meal_type": e.get("meal_type"),
            "food": e.get("food_name"), "quantity": qty, "unit": e.get("unit"),
            "calories": total("calories"), "protein_g": total("protein"), "carbs_g": total("carbs"),
            "fat_g": total("fat"), "saturated_fat_g": total("saturated_fat"), "fiber_g": total("dietary_fiber"),
            "sugar_g": total("sugars"), "sodium_mg": total("sodium"), "notes": e.get("notes")}


def food_entries(client: SparkyClient, start: date, end: date) -> list[dict]:
    """Every food entry in [start, end] (portion already converted to this entry's total nutrition).
    id is the SparkyFitness entry id (undo_sparky_entry / DELETE .../nutrition/entries/{id}); source=body_assistant = written by this system's AI."""
    return [_food_entry(e) for e in client.get(f"/food-entries/range/{start.isoformat()}/{end.isoformat()}")]


def nutrition(client: SparkyClient, start: date, end: date, entries: bool = True) -> dict:
    """Per-day calories / macro totals and the day's targets in [start, end]; with entries=True each food entry is attached.
    Days without records total 0 (not necessarily nothing eaten, maybe just not logged).
    Targets are looked up by date (goal_for_date, which follows the weekly goal plan switching training / rest days); the default goal in the report endpoint is not used.
    SparkyFitness-only view: the app uses nutrition/daily.py instead (goals from goals/nutrition.py, sugar extras, coverage)."""
    days = client.get("/reports/nutrition-trends-with-goals", startDate=start.isoformat(), endDate=end.isoformat())
    out = {"days": []}
    for d in days:
        g = goal_for_date(client, date.fromisoformat(d["date"][:10]))
        out["days"].append({"date": d["date"], "logged": None, "calories": d["calories"], "protein_g": d["protein"],
                            "carbs_g": d["carbs"], "fat_g": d["fat"],
                            "goal": {"name": g["name"], "calories": g["calories"], "protein_g": g["protein_g"],
                                     "carbs_g": g["carbs_g"], "fat_g": g["fat_g"]}})
    rows = food_entries(client, start, end)
    logged = {r["date"] for r in rows}
    for d in out["days"]:
        d["logged"] = d["date"] in logged
    if entries:
        out["entries"] = sorted(rows, key=lambda r: (r["date"], r["time"] or ""))
    return out


# ---------------------------------------------------------------- weight / body measurements
def weight(client: SparkyClient, start: date, end: date) -> list[dict]:
    """Weigh-in / body data records in [start, end] (SparkyFitness check-ins), only those with values."""
    rows = client.get(f"/measurements/check-in-measurements-range/{start.isoformat()}/{end.isoformat()}")
    keys = {"weight": "weight_kg", "waist": "waist_cm", "body_fat_percentage": "body_fat_pct",
            "muscle_mass_kg": "muscle_mass_kg", "height": "height_cm"}
    out = []
    for r in rows:
        vals = {v: r.get(k) for k, v in keys.items() if r.get(k) is not None}
        if vals:
            out.append({"date": r["entry_date"][:10], **vals})
    return sorted(out, key=lambda r: r["date"])


def weekly_weight_average(rows: list[dict]) -> list[dict]:
    """Average weight per week (week starts Monday); the rules in body-management.md look at the weekly average."""
    weeks: dict[date, list[float]] = {}
    for r in rows:
        if "weight_kg" in r:
            d = date.fromisoformat(r["date"])
            weeks.setdefault(d - timedelta(days=d.weekday()), []).append(r["weight_kg"])
    return [{"week_start": w.isoformat(), "avg_kg": round(sum(v) / len(v), 2), "n": len(v)}
            for w, v in sorted(weeks.items())]


# ---------------------------------------------------------------- exercise library, workout plan, food goals (used by the rules engine)
def _json_list(v) -> list:
    """SparkyFitness equipment / primary_muscles are sometimes a JSON string, sometimes an array."""
    if v is None:
        return []
    if isinstance(v, str):
        try:
            v = json.loads(v)
        except ValueError:
            return [v]
    return list(v) if isinstance(v, (list, tuple)) else [v]


def exercises(client: SparkyClient) -> list[dict]:
    """This user's own exercise library (self-created + migrated); per exercise: id, name, category, primary muscles, description."""
    out, page = [], 1
    while True:
        res = client.get("/exercises", currentPage=page, itemsPerPage=100, ownershipFilter="mine")
        out += res["exercises"]
        if not res["exercises"] or len(out) >= res["totalCount"]:
            break
        page += 1
    return [{"id": e["id"], "name": e["name"], "category": e.get("category"), "modality": e.get("modality"),
             "source_id": e.get("source_id"), "primary_muscles": _json_list(e.get("primary_muscles")),
             "description": e.get("description")} for e in out]


def workout_presets(client: SparkyClient) -> dict[int, dict]:
    """Workout templates: id -> {name, exercises: [{exercise_id, name, progression_mode, rep_goal, increment_value, sets}]}"""
    out, page = {}, 1
    while True:
        res = client.get("/workout-presets", page=page, limit=100)
        for p in res["presets"]:
            out[p["id"]] = {"id": p["id"], "name": p["name"], "exercises": [
                {"exercise_id": x["exercise_id"], "name": x.get("exercise_name"), "category": x.get("category"),
                 "progression_mode": x.get("progression_mode"), "rep_goal": x.get("rep_goal"),
                 "increment_value": x.get("increment_value"),
                 "sets": [{"set": s["set_number"], "type": s.get("set_type"), "reps": s.get("reps"),
                           "weight_kg": s.get("weight"), "duration_s": s.get("duration"), "notes": s.get("notes")}
                          for s in sorted(x.get("sets") or [], key=lambda s: s["set_number"])]}
                for x in p.get("exercises") or []]}
        if not res["presets"] or len(out) >= res.get("total", 0):
            break
        page += 1
    return out


def workout_plans(client: SparkyClient) -> list[dict]:
    """Weekly workout plan (SparkyFitness workout plan template). day_of_week: 0 = Sunday ... 6 = Saturday."""
    return [{"id": t["id"], "name": t["plan_name"], "start_date": (t.get("start_date") or "")[:10] or None,
             "end_date": (t.get("end_date") or "")[:10] or None, "is_active": t.get("is_active"),
             "schedule_type": t.get("schedule_type"),
             "assignments": [{"day_of_week": a["day_of_week"], "sort_order": a.get("sort_order") or 0,
                              "workout_preset_id": a.get("workout_preset_id"),
                              "workout_preset_name": a.get("workout_preset_name"),
                              "exercise_id": a.get("exercise_id"), "exercise_name": a.get("exercise_name"),
                              "sets": a.get("sets") or []} for a in t.get("assignments") or []]}
            for t in client.get("/workout-plan-templates")]


def goal_for_date(client: SparkyClient, day: date) -> dict:
    """Food goal in effect on a given day (follows the weekly goal plan switching training / rest days).
    Note the goal in /reports/nutrition-trends-with-goals is the default goal and does not follow the weekly goal plan, so it is queried separately.
    Only the active weekly goal plan is followed (dates before it get the default goal), so past dates are not reliable:
    goals/nutrition.py uses this only as the fallback before a user's first Body Engine goal version."""
    g = client.get(f"/goals/by-date/{day.isoformat()}")
    return {"date": day.isoformat(), "name": g.get("preset_name"), "calories": g.get("calories"),
            "protein_g": g.get("protein"), "carbs_g": g.get("carbs"), "fat_g": g.get("fat"),
            "water_ml": g.get("water_goal_ml")}
