#!/usr/bin/env python3
"""Generate body_engine/src/body_engine/web/static/muscle-body-data.js (male / female, front / back muscle map paths).

Source: the npm package @mjcdev/react-body-highlighter 0.0.4 (MIT, Copyright (c) 2022 ELABBASSI Hicham; based on
react-native-body-highlighter). Only the SVG path data is used; rendering is ours (web/static/muscle-map.js).

    npm pack @mjcdev/react-body-highlighter@0.0.4 && tar xzf mjcdev-react-body-highlighter-0.0.4.tgz
    python3 tools/gen_muscle_body_data.py package > body_engine/src/body_engine/web/static/muscle-body-data.js
"""
import json
import re
import sys
from pathlib import Path

pkg = Path(sys.argv[1])
SETS = {("male", "front"): "bodyFront", ("male", "back"): "bodyBack",
        ("female", "front"): "bodyFemaleFront", ("female", "back"): "bodyFemaleBack"}
VIEWBOX = {("male", "front"): "0 0 724 1448", ("male", "back"): "724 0 724 1448",
           ("female", "front"): "-50 -40 734 1538", ("female", "back"): "756 0 774 1448"}
NEUTRAL = {"hair", "head", "hands", "feet", "ankles", "knees", "tibialis"}   # drawn as the plain body, never coloured


def short(d: str) -> str:
    d = re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)
    # "1.2.64" is two numbers in SVG path shorthand; spell the separator out (also keeps it from looking like an IP address)
    while (n := re.sub(r"(\d\.\d+)(?=\.\d)", r"\1 ", d)) != d:
        d = n
    return d


def strings(block: str) -> list[str]:
    return [short(s) for s in re.findall(r'"([^"]+)"', block)]


def parts(src: str) -> list[list]:
    out = []
    for m in re.finditer(r'slug:\s*"([a-z-]+)".*?path:\s*\{(.*?)\n\t\t\},?', src, re.S):
        slug, body = m.group(1), m.group(2)
        paths = []
        for key in ("common", "left", "right"):
            k = re.search(key + r":\s*\[(.*?)\]\s*,?\s*(?=\n\t\t\t\w+:|\Z)", body, re.S)
            if k:
                paths += strings(k.group(1))
        out.append([slug, paths])
    return out


def outline(sex: str, side: str) -> str:
    w = (pkg / "components" / f"Svg{'Female' if sex == 'female' else 'Male'}Wrapper.tsx").read_text()
    blocks = re.findall(r'side === "(front|back)" && \(\s*<path.*?\bd="([^"]+)"', w, re.S)
    return short(dict(blocks)[side])


data = {}
for (sex, side), name in SETS.items():
    src = (pkg / "assets" / f"{name}.ts").read_text()
    ps = parts(src)
    data.setdefault(sex, {})[side] = {
        "vb": VIEWBOX[(sex, side)], "outline": outline(sex, side),
        "base": [p for s, pp in ps if s in NEUTRAL for p in pp],
        "muscles": [[s, pp] for s, pp in ps if s not in NEUTRAL],
    }
print("/* Generated by tools/gen_muscle_body_data.py — do not edit. Male / female, front / back body paths for the muscle load map.\n"
      "   Source: @mjcdev/react-body-highlighter 0.0.4 (https://github.com/MichaelMjc/react-body-highlighter), MIT License,\n"
      "   Copyright (c) 2022 ELABBASSI Hicham (based on react-native-body-highlighter) — see docs/LICENSES.md. Only the paths are used. */")
print("window.BodyMuscleBodies = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";")
