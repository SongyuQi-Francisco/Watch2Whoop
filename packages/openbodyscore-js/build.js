#!/usr/bin/env node
// Builds dist/openbodyscore.js (one file, one global `OpenBodyScore`, no dependencies, ES2020, no DOM / Node APIs) from src/*.js
// in name order, and dist/manifest.json (version, sha256, size, algorithm versions).
//   node build.js          write dist/
//   node build.js --check  exit 1 when dist/ is not what src/ builds (CI)
"use strict";
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = __dirname;
const DIST = path.join(ROOT, "dist");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));

// 2.0.0 packages (docs/ios-native-2.0.md section 2.2) add src/3N_<pkg>.js and extend OBS.ALGO_VERSIONS.<key>; only
// 20_api.js creates the object, so a package can never drop another package's key.
const ALGO_VERSIONS_OWNER = "20_api.js";
const REASSIGN = /\bOBS\.ALGO_VERSIONS\s*=(?!=)/;

function bundle() {
  const files = fs.readdirSync(path.join(ROOT, "src")).filter((f) => f.endsWith(".js")).sort();
  for (const f of files) {
    if (f !== ALGO_VERSIONS_OWNER && REASSIGN.test(fs.readFileSync(path.join(ROOT, "src", f), "utf8"))) {
      console.error(`src/${f} reassigns OBS.ALGO_VERSIONS: add your key instead (OBS.ALGO_VERSIONS.<key> = ...)`);
      process.exit(1);
    }
  }
  const parts = files.map((f) => `// ---- src/${f}\n` + fs.readFileSync(path.join(ROOT, "src", f), "utf8").trimEnd() + "\n");
  return `/*! openbodyscore-js ${pkg.version} | AGPL-3.0; the parts ported from packages/openbodyscore are Apache-2.0 (NOTICE)
 * Watch2Whoop scoring algorithms: a port of packages/openbodyscore and the pure scoring parts of body_engine.
 * Generated by packages/openbodyscore-js/build.js from src/ — do not edit by hand. */
(function (root) {
"use strict";
var OBS = { BUNDLE_VERSION: ${JSON.stringify(pkg.version)} };
${parts.join("\n")}
root.OpenBodyScore = OBS;
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
}

function manifest(code) {
  // load the bundle the way JavaScriptCore does: a bare context with only the language built-ins
  const ctx = vm.createContext({});
  vm.runInContext(code, ctx, { filename: "openbodyscore.js" });
  const obs = ctx.OpenBodyScore;
  return {
    name: "openbodyscore-js",
    version: pkg.version,
    file: "openbodyscore.js",
    sha256: crypto.createHash("sha256").update(code, "utf8").digest("hex"),
    size: Buffer.byteLength(code, "utf8"),
    algo_versions: JSON.parse(JSON.stringify(obs.ALGO_VERSIONS)),
    global: "OpenBodyScore",
  };
}

const code = bundle();
const outJs = path.join(DIST, "openbodyscore.js");
const outMan = path.join(DIST, "manifest.json");
// The maintainer's Ed25519 signature (`body-engine algo-sign`, docs/ios-native-app.md 6.3) is kept while it still
// belongs to these exact bytes; a rebuilt bundle drops it and has to be signed again.
function withSignature(m) {
  let old = null;
  try { old = JSON.parse(fs.readFileSync(outMan, "utf8")); } catch (e) { old = null; }
  if (old && old.signature && old.sha256 === m.sha256) return { ...m, signature: old.signature, key_id: old.key_id };
  return m;
}
const man = JSON.stringify(withSignature(manifest(code)), null, 2) + "\n";
if (process.argv.includes("--check")) {
  const same = (f, s) => fs.existsSync(f) && fs.readFileSync(f, "utf8") === s;
  if (!same(outJs, code) || !same(outMan, man)) {
    console.error("dist/ is out of date: run `node packages/openbodyscore-js/build.js` and commit dist/");
    process.exit(1);
  }
  console.log("dist/ is up to date");
} else {
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(outJs, code);
  fs.writeFileSync(outMan, man);
  console.log(`wrote dist/openbodyscore.js (${Buffer.byteLength(code)} bytes) and dist/manifest.json`);
}
